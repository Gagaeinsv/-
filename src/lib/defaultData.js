export async function ensureSeeded(prisma) {
  const existingProfile = await prisma.profile.findFirst();
  if (existingProfile) return existingProfile;

  const created = await prisma.profile.create({
    data: {
      ...defaultProfile,
      specializations: {
        create: defaultSpecializations.map((s) => ({
          name: s.name,
          description: s.description,
        })),
      },
      paymentSettings: {
        create: {
          iban: defaultPaymentSettings.iban,
          bankName: defaultPaymentSettings.bankName,
          edrpou: defaultPaymentSettings.edrpou,
          monoLink: defaultPaymentSettings.monoLink,
          paypalLink: defaultPaymentSettings.paypalLink,
          paypalEmail: defaultPaymentSettings.paypalEmail,
          useIban: defaultPaymentSettings.useIban,
          useMono: defaultPaymentSettings.useMono,
          usePaypal: defaultPaymentSettings.usePaypal,
        },
      },
    },
    include: {
      specializations: true,
      paymentSettings: true,
    },
  });

  const existingServices = await prisma.service.count();
  if (existingServices === 0) {
    for (const s of defaultServices) {
      await prisma.service.create({ data: s });
    }
  }

  const existingDocs = await prisma.legalDoc.count();
  if (existingDocs === 0) {
    for (const d of defaultLegalDocs) {
      await prisma.legalDoc.create({ data: d });
    }
  }

  return created;
}

export function getFallbackPayload() {
  return {
    success: true,
    profile: {
      ...defaultProfile,
      specializations: defaultSpecializations.map((s, idx) => ({ id: idx + 1, profileId: 1, ...s })),
      paymentSettings: defaultPaymentSettings,
    },
    services: defaultServices.map((s, idx) => ({ id: idx + 1, ...s })),
    legalDocs: defaultLegalDocs.map((d, idx) => ({ id: idx + 1, ...d })),
    scheduleOverrides: [],
  };
}
